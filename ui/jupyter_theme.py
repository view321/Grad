from ui import tokens

BANNER = "/* generated by ui/jupyter_theme.py — edit the tokens, not this file */"


def target() -> Path:
    """Where JupyterLab looks, given the config dir `tools/lab.py` sets."""
    return paths.root() / "config" / "jupyter" / "custom" / "custom.css"


def repo_path() -> Path:
    """The version-controlled copy.

    Module-relative rather than `paths.root()`-derived: this file is part of the
    repository, not of a workspace, and `GRAD_ROOT` points at a temp directory
    under test. The two agree in every real run because `GRAD_ROOT` is the
    checkout.
    """
    return Path(__file__).resolve().parents[1] / "config" / "jupyter" / "custom" / "custom.css"


