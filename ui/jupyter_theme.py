"""The JupyterLab half of the design, generated from the same tokens.

The notebook window is a real Lab iframe on its own port, so it is a different
origin and its interior cannot be styled from the host page. The handoff asks
for a **pinned theme extension**. This does the same job with a `custom.css`
file instead, and the trade is worth stating plainly:

* A theme extension means npm, TypeScript, a cookiecutter, a build step in
  packaging, and a rebuild on every JupyterLab minor -- the JupyterLab 3→4 break
  is exactly what killed the Tabnine extension, and the `lab` extra pins every
  version precisely because of it.
* JupyterLab 4 loads `{JUPYTER_CONFIG_DIR}/custom/custom.css` when started with
  `--custom-css`. `tools/lab.py` already sets `JUPYTER_CONFIG_DIR` to
  `config/jupyter`, so this is a plain file and one flag.

The cost of the cheaper path is that `custom.css` cannot register a *named*
theme, so `overrides.json` selects `JupyterLab Light` and this sheet re-tokens
it, rather than selecting a theme called "Grad Paper". Everything the handoff
lists -- `--jp-layout-color*`, `--jp-border-color*`,
`--jp-cell-editor-background`, the font families, `.jp-InputArea-prompt`,
`.jp-OutputArea-output`, `.jp-RenderedText` -- is set either way.

Generated rather than hand-written so the notebook interior cannot drift from
the chrome above it: `tests/test_ui_theme.py` fails if the file on disk stops
matching `stylesheet()`.

    python -m ui.jupyter_theme --write
"""

from __future__ import annotations

